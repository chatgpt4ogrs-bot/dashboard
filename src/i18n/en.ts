/** Mensagens do servidor com partes variáveis. */
const SERVER_PATTERNS: [RegExp, (...groups: string[]) => string][] = [
  [/^Campo "(.+)" inválido\.$/, (field) => `Invalid field "${field}".`],
  [/^O dispositivo respondeu com HTTP (\d+)\.$/, (status) => `The device responded with HTTP ${status}.`],
  [/^A senha do Super usuário precisa ter pelo menos (\d+) caracteres\.$/, (n) => `The Super user password must be at least ${n} characters.`],
  [/^Latência alta \((\d+) ms\)\.$/, (ms) => `High latency (${ms} ms).`],
  [/^Caiu e voltou (\d+)x na última hora\.$/, (n) => `Went down and came back ${n}x in the last hour.`],
  [/^(\d+) de (\d+) verificações falharam na última hora\.$/, (f, t) => `${f} of ${t} checks failed in the last hour.`],
  [/^(.*) \(condomínio (.*) excluído\)$/, (name, condo) => `${name} (condominium ${condo} deleted)`],
  [
    /^Conectado ao PostgreSQL (.+?)\. O banco "(.+)" (já existe e será usado|será criado)\.$/,
    (version, db, action) =>
      `Connected to PostgreSQL ${version}. The database "${db}" ${action === 'será criado' ? 'will be created' : 'already exists and will be used'}.`,
  ],
  [/^Banco de dados indisponível: (.+)$/s, (reason) => `Database unavailable: ${translateServerMessage(reason)}`],
];

function translateServerMessage(message: string): string {
  const exact = SERVER_MESSAGES[message];
  if (exact) return exact;
  for (const [pattern, build] of SERVER_PATTERNS) {
    const match = pattern.exec(message);
    if (match) return build(...match.slice(1));
  }
  return message;
}

